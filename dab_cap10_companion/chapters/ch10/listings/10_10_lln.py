population = pay["amount_zmw"].to_numpy()
mu = population.mean()
draws = rng.choice(population, size=5_000)
running = draws.cumsum() / np.arange(1, len(draws) + 1)

fig, ax = plt.subplots(figsize=(8, 3.6))
ax.plot(np.arange(1, len(draws) + 1), running, linewidth=1.4)
ax.axhline(mu, color="#1B2A41", linestyle="--", linewidth=1)
ax.text(5_000, mu + 25, f"population mean K{mu:,.0f}", ha="right", fontsize=9)
ax.set_xscale("log")
ax.xaxis.set_major_formatter("{x:,.0f}")
ax.set_xlabel("Number of orders sampled (log scale)")
ax.set_ylabel("Running mean order value (K)")
ax.set_title("The sample mean settles on the population mean as the sample grows")
fig.savefig(FIG + "fig_10_4_lln.png", dpi=200)
plt.close(fig)
for n in [10, 100, 1_000, 5_000]:
    print(f"after {n:>5,} orders: running mean K{running[n - 1]:,.0f}")
print(f"population mean K{mu:,.0f}")
