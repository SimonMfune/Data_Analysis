"""Page 5, Insights: recommendations from a language model, grounded, validated and disclosed."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # the app folder

import json  # noqa: E402

import streamlit as st  # noqa: E402

import ui  # noqa: E402
from workspace import insights  # noqa: E402
from workspace.llm_client import LLMError, get_client  # noqa: E402

st.title("💡 Insights")
result = ui.require("model", "Fit a model first.", "views/model.py", "Go to Model")
df = st.session_state["prepared"]["df"]
data = insights.payload(df, result)

st.write("The model's results are summarised below. Only this summary is sent to the language model: "
         "no rows of data.")
with st.expander("What will be sent (JSON)", expanded=False):
    st.code(json.dumps(data, indent=2), language="json")
audience = st.text_input("Who are the recommendations for?", "The marketing manager", key="i_audience")

try:
    client = get_client(cache=True)
except LLMError as error:
    st.error(f"The language model is not configured: {error}")
    st.stop()
st.caption(f"Provider: {client.provider.name} · model: {client.model}"
           + (" (offline practice mode)" if client.provider.name == "mock" else ""))

if st.button("Generate recommendations", type="primary"):
    system, prompt = insights.prompt(data, audience)
    try:
        reply = client.complete(prompt, system=system)
    except LLMError as error:
        st.error(str(error))
        st.stop()
    parsed, problems = insights.validate(reply.text, data)
    st.session_state["insights"] = {"reply": parsed, "problems": problems, "raw": reply.text,
                                    "provider": reply.provider, "model": reply.model}

if "insights" in st.session_state:
    ins = st.session_state["insights"]
    st.warning("**AI-generated draft.** Written by a language model from the model output above. "
               "Check it before acting on it.", icon="🤖")
    if ins["reply"] is None:
        st.error("The reply could not be used: " + "; ".join(ins["problems"]))
        st.code(ins["raw"])
        st.stop()
    if ins["problems"]:
        st.error(f"{len(ins['problems'])} figure(s) could not be verified against the model output. "
                 "These recommendations are excluded from the report.")
        for p in ins["problems"]:
            st.write("- " + p)
    else:
        st.success("Every figure and feature was verified against the model output.")
    for i, rec in enumerate(ins["reply"].recommendations, 1):
        st.markdown(f"**{i}. {rec.title}**  \n{rec.detail}  \n"
                    f"*Evidence: {', '.join(f'{e:g}' for e in rec.evidence)} · features: {', '.join(rec.features)}*")
    st.markdown("**Caveats.** " + " ".join(ins["reply"].caveats))
    st.caption(f"Confidence: {ins['reply'].confidence} · generated by {ins['provider']} ({ins['model']})")
st.page_link("views/report.py", label="Next: report", icon="➡️")
